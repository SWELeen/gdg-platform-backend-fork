BEGIN;

-- Rules must work without the optional demo seed; retain compatible local IDs.
LOCK TABLE "committee" IN SHARE ROW EXCLUSIVE MODE;
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM "committee" c
        JOIN (VALUES ('DATA', 'Data'), ('PR', 'Public Relations')) AS wanted(code, name)
          ON c.committee_code = wanted.code
        WHERE c.committee_name IS DISTINCT FROM wanted.name OR c.parent_committee_id IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'committee_permission_requires_matching_committees';
    END IF;
END;
$$;
INSERT INTO "committee" ("committee_code", "committee_name")
SELECT wanted.code, wanted.name
FROM (VALUES ('DATA', 'Data'), ('PR', 'Public Relations')) AS wanted(code, name)
WHERE NOT EXISTS (SELECT 1 FROM "committee" c WHERE c.committee_code = wanted.code);

CREATE TABLE "committee_permission" (
    "id" INTEGER GENERATED BY DEFAULT AS IDENTITY,
    "committee_id" INTEGER,
    "committee_role" TEXT NOT NULL,
    "code" TEXT NOT NULL,
    "applies_to" TEXT NOT NULL,
    "include_sub_committees" BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT "committee_permission_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "committee_permission_committee_id_fkey" FOREIGN KEY ("committee_id") REFERENCES "committee"("committee_id") ON DELETE RESTRICT ON UPDATE NO ACTION,
    CONSTRAINT "committee_permission_code_fkey" FOREIGN KEY ("code") REFERENCES "permission"("code") ON DELETE RESTRICT ON UPDATE NO ACTION,
    CONSTRAINT "committee_permission_committee_role_check" CHECK ("committee_role" IN ('Leader', 'Co-Leader', 'Member')),
    CONSTRAINT "committee_permission_applies_to_check" CHECK ("applies_to" IN ('own', 'all')),
    CONSTRAINT "committee_permission_check" CHECK ("committee_id" IS NOT NULL OR "applies_to" = 'own')
);
CREATE UNIQUE INDEX "uq_committee_permission" ON "committee_permission" (COALESCE("committee_id", 0), "committee_role", "code", "applies_to");
CREATE INDEX "committee_permission_committee_role_idx" ON "committee_permission" ("committee_id", "committee_role");
CREATE INDEX "committee_permission_code_idx" ON "committee_permission" ("code");

-- Local committee IDs are resolved by code; no memberships or global role grants.
INSERT INTO "committee_permission" ("committee_id", "committee_role", "code", "applies_to", "include_sub_committees")
SELECT c.committee_id, rule.position, rule.code, rule.applies_to, false
FROM (VALUES
    ('DATA', 'Leader', 'events.create', 'own'),
    ('DATA', 'Co-Leader', 'events.create', 'own'),
    ('PR', 'Leader', 'registrants.view', 'all'),
    ('PR', 'Co-Leader', 'registrants.view', 'all'),
    ('PR', 'Member', 'registrants.view', 'all'),
    ('PR', 'Leader', 'registrations.review', 'all'),
    ('PR', 'Co-Leader', 'registrations.review', 'all'),
    ('PR', 'Member', 'registrations.review', 'all')
) AS rule(committee_code, position, code, applies_to)
JOIN "committee" c ON c.committee_code = rule.committee_code;

COMMIT;
