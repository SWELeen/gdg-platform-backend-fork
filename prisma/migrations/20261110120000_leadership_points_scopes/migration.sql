BEGIN;

-- Committee leaders can be awarded points by club leadership without being a
-- member of the recipient's committee. Keep the recipient committee-scoped,
-- while recording the awarder as a member account.
ALTER TABLE "committee_point_entry"
  DROP CONSTRAINT "committee_point_entry_awarder_committee_fkey",
  ADD CONSTRAINT "committee_point_entry_awarder_member_fkey"
    FOREIGN KEY ("awarded_by_member_id") REFERENCES "member"("member_id")
    ON DELETE RESTRICT ON UPDATE NO ACTION;

-- The overall Developer Committees Leader is a global role, so their own
-- points use a separate global ledger rather than being attached to one team.
CREATE TABLE "global_point_entry" (
  "point_entry_id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "member_id" INTEGER NOT NULL,
  "awarded_by_member_id" INTEGER NOT NULL,
  "points_delta" INTEGER NOT NULL,
  "reason" VARCHAR(500) NOT NULL,
  "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "global_point_entry_delta_check" CHECK ("points_delta" <> 0),
  CONSTRAINT "global_point_entry_recipient_fkey" FOREIGN KEY ("member_id")
    REFERENCES "member"("member_id") ON DELETE RESTRICT ON UPDATE NO ACTION,
  CONSTRAINT "global_point_entry_awarder_fkey" FOREIGN KEY ("awarded_by_member_id")
    REFERENCES "member"("member_id") ON DELETE RESTRICT ON UPDATE NO ACTION
);
CREATE INDEX "global_point_entry_member_created_idx"
  ON "global_point_entry"("member_id", "created_at", "point_entry_id");
CREATE INDEX "global_point_entry_created_idx"
  ON "global_point_entry"("created_at", "point_entry_id");

INSERT INTO "permission" ("code", "description", "scope", "is_sensitive") VALUES
  ('club.points.manage', 'Award points to committee leaders and the overall Developer Committees Leader', 'global', true),
  ('developer_committees.points.manage', 'Award points to leaders of developer subcommittees', 'global', true)
ON CONFLICT ("code") DO NOTHING;

INSERT INTO "role_permission" ("role_code", "code") VALUES
  ('GROUP_LEADER', 'club.points.manage'),
  ('GROUP_CO_LEADER', 'club.points.manage'),
  ('DEVELOPER_COMMITTEES_LEADER', 'developer_committees.points.manage')
ON CONFLICT ("role_code", "code") DO NOTHING;

COMMIT;
